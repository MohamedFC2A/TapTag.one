const START_CODE_B = 104;
const STOP_CODE = 106;

export interface BarcodeBar {
  x: number;
  width: number;
}

/**
 * Encodes an ASCII string into Code 128-B bars.
 */
export function generateCode128Bars(text: string): { bars: BarcodeBar[]; totalUnits: number } {
  const codes: number[] = [START_CODE_B];
  let checkSum = START_CODE_B;

  for (let i = 0; i < text.length; i++) {
    const charCode = text.charCodeAt(i);
    // ASCII 32 to 126 maps to 0 to 94 in Code 128
    const val = charCode >= 32 && charCode <= 126 ? charCode - 32 : 0;
    codes.push(val);
    checkSum += val * (i + 1);
  }

  codes.push(checkSum % 103);
  codes.push(STOP_CODE);

  const bars: BarcodeBar[] = [];
  let currentX = 10; // Quiet zone

  codes.forEach((code) => {
    const pattern = CODE128_PATTERNS[code];
    if (!pattern) return;

    for (let p = 0; p < pattern.length; p++) {
      const width = pattern[p];
      if (p % 2 === 0) {
        // Bar (black/colored)
        bars.push({ x: currentX, width });
      }
      currentX += width;
    }
  });

  currentX += 10; // Ending quiet zone

  return { bars, totalUnits: currentX };
}

/**
 * Returns an inline SVG string for the barcode
 */
export function renderCode128Svg(text: string, height = 48, barColor = "#FFFFFF"): string {
  const { bars, totalUnits } = generateCode128Bars(text);
  const barElements = bars
    .map((b) => `<rect x="${b.x}" y="0" width="${b.width}" height="${height}" fill="${barColor}" />`)
    .join("");

  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${totalUnits} ${height}" preserveAspectRatio="none" style="display:block;width:100%;height:100%;">${barElements}</svg>`;
}
